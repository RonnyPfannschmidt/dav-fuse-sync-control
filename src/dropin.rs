//! systemd drop-in generation and parsing.
//!
//! The critical property, tested directly below: `davfs-sync mount <name>`
//! (foreground) and `davfs-sync daemon` (under systemd) must end up with a
//! byte-identical configuration. Without that you spend an afternoon debugging
//! a mount that only misbehaves under systemd.

use std::collections::BTreeMap;
use std::path::PathBuf;

use anyhow::{Context, Result};

/// Written by `setup`; the `50-` prefix leaves room for a hand-written
/// `60-local.conf` that survives re-running it.
pub const DROPIN_FILE: &str = "50-davfs-sync.conf";

/// The drop-in directory for a mount.
///
/// Note `.service.d`, not `.d`: systemd requires the full unit name.
pub fn dropin_dir(name: &str) -> Result<PathBuf> {
    let config = dirs::config_dir().context("no XDG config directory")?;
    Ok(config
        .join("systemd/user")
        .join(format!("davfs-sync@{name}.service.d")))
}

pub fn dropin_path(name: &str) -> Result<PathBuf> {
    Ok(dropin_dir(name)?.join(DROPIN_FILE))
}

/// A mount name goes straight into a unit name and a filesystem path, so it is
/// validated rather than trusted.
pub fn validate_name(name: &str) -> Result<()> {
    if name.is_empty() {
        anyhow::bail!("the mount name cannot be empty");
    }
    if name.starts_with('-') {
        anyhow::bail!("the mount name cannot start with '-'");
    }
    if name == "." || name == ".." {
        anyhow::bail!("the mount name cannot be '.' or '..'");
    }
    for bad in ['/', '@', '\0', '\n', '%'] {
        if name.contains(bad) {
            anyhow::bail!("the mount name cannot contain {bad:?}");
        }
    }
    if !name
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '.')
    {
        anyhow::bail!("the mount name may only contain letters, digits, '-', '_' and '.'");
    }
    Ok(())
}

/// Render the `Environment=` lines for a mount.
///
/// Deliberately omits spec/03's `ReadWritePaths=`: those are no-ops without the
/// `Protect*` directives, and if they ever did take effect they would create
/// the private mount namespace that hides the mount from the rest of the
/// session.
pub fn render(vars: &BTreeMap<String, String>) -> String {
    let mut out = String::from(
        "# Generated by `davfs-sync setup` -- edits will be overwritten.\n\
         # Put local overrides in 60-local.conf instead.\n\
         [Service]\n",
    );
    for (k, v) in vars {
        out.push_str(&format!("Environment={}\n", quote(k, v)));
    }
    out
}

/// systemd's `Environment=` quoting.
///
/// `%` must be escaped as `%%` or systemd performs specifier expansion on it --
/// the sharpest edge in the whole generator, and the reason a mount point
/// containing a percent sign would otherwise silently point somewhere else.
fn quote(key: &str, value: &str) -> String {
    let escaped = value.replace('%', "%%");
    let needs_quotes = escaped.is_empty()
        || escaped
            .chars()
            .any(|c| c.is_whitespace() || c == '"' || c == '\'' || c == '\\' || c == '$');

    if needs_quotes {
        let inner = escaped.replace('\\', "\\\\").replace('"', "\\\"");
        format!("\"{key}={inner}\"")
    } else {
        format!("{key}={escaped}")
    }
}

/// Parse `Environment=` assignments out of a drop-in.
///
/// Handles both bare and quoted forms, and undoes `%%`.
pub fn parse(contents: &str) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();

    for line in contents.lines() {
        let line = line.trim();
        if line.starts_with('#') || line.starts_with(';') {
            continue;
        }
        let Some(rest) = line.strip_prefix("Environment=") else {
            continue;
        };
        let rest = rest.trim();

        let assignment = if let Some(inner) = rest.strip_prefix('"') {
            // Quoted: read to the closing quote, honouring backslash escapes.
            let mut buf = String::new();
            let mut chars = inner.chars();
            while let Some(c) = chars.next() {
                match c {
                    '\\' => {
                        if let Some(next) = chars.next() {
                            buf.push(next);
                        }
                    }
                    '"' => break,
                    _ => buf.push(c),
                }
            }
            buf
        } else {
            rest.to_string()
        };

        if let Some((k, v)) = assignment.split_once('=') {
            out.insert(k.to_string(), v.replace("%%", "%"));
        }
    }
    out
}

/// Write the drop-in, creating the directory.
pub fn write(name: &str, vars: &BTreeMap<String, String>) -> Result<PathBuf> {
    validate_name(name)?;
    let dir = dropin_dir(name)?;
    std::fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    let path = dir.join(DROPIN_FILE);
    std::fs::write(&path, render(vars)).with_context(|| format!("writing {}", path.display()))?;
    Ok(path)
}

/// Read a mount's drop-in, if it has one.
pub fn read(name: &str) -> Result<Option<BTreeMap<String, String>>> {
    let path = dropin_path(name)?;
    match std::fs::read_to_string(&path) {
        Ok(s) => Ok(Some(parse(&s))),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e).with_context(|| format!("reading {}", path.display())),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn vars(pairs: &[(&str, &str)]) -> BTreeMap<String, String> {
        pairs
            .iter()
            .map(|(k, v)| (k.to_string(), v.to_string()))
            .collect()
    }

    /// The property the whole module exists for.
    #[test]
    fn render_and_parse_round_trip() {
        let original = vars(&[
            (
                "DAVFS_URL",
                "https://cloud.example.com/remote.php/dav/files/alice/",
            ),
            ("DAVFS_USERNAME", "alice"),
            ("DAVFS_MOUNT_POINT", "/home/alice/Cloud"),
            ("DAVFS_READ_ONLY", "true"),
        ]);
        assert_eq!(parse(&render(&original)), original);
    }

    #[test]
    fn values_with_spaces_survive() {
        let original = vars(&[("DAVFS_MOUNT_POINT", "/home/alice/My Cloud Files")]);
        let rendered = render(&original);
        assert!(rendered.contains('"'), "not quoted: {rendered}");
        assert_eq!(parse(&rendered), original);
    }

    /// A percent sign must not be interpreted as a systemd specifier.
    #[test]
    fn percent_is_escaped_and_recovered() {
        let original = vars(&[("DAVFS_MOUNT_POINT", "/home/alice/100%done")]);
        let rendered = render(&original);
        assert!(
            rendered.contains("100%%done"),
            "percent not escaped: {rendered}"
        );
        assert_eq!(
            parse(&rendered),
            original,
            "the percent did not survive the round trip"
        );
    }

    #[test]
    fn hostile_values_survive() {
        for value in [
            "/path/with \"quotes\"",
            "/path/with 'single'",
            "/path/with\\backslash",
            "/path/with$dollar",
            "/tmp/100%done and spaces",
            "",
        ] {
            let original = vars(&[("DAVFS_MOUNT_POINT", value)]);
            let rendered = render(&original);
            assert_eq!(
                parse(&rendered),
                original,
                "round trip failed for {value:?}\nrendered: {rendered}"
            );
        }
    }

    #[test]
    fn comments_and_other_directives_are_ignored() {
        let text = "\
# a comment
[Service]
Environment=DAVFS_URL=https://example.com/
ExecStart=/usr/bin/something
; another comment
Environment=\"DAVFS_MOUNT_POINT=/home/a/My Files\"
";
        let got = parse(text);
        assert_eq!(got.len(), 2);
        assert_eq!(got["DAVFS_URL"], "https://example.com/");
        assert_eq!(got["DAVFS_MOUNT_POINT"], "/home/a/My Files");
    }

    #[test]
    fn the_generated_file_carries_a_warning_and_a_service_section() {
        let out = render(&vars(&[("DAVFS_URL", "https://x/")]));
        assert!(out.contains("[Service]"));
        assert!(out.contains("overwritten"));
        assert!(out.contains("60-local.conf"));
    }

    /// spec/03's example includes ReadWritePaths=; including it would be an
    /// invitation to "complete" the sandboxing and hide the mount.
    #[test]
    fn no_sandboxing_directives_are_emitted() {
        let out = render(&vars(&[("DAVFS_URL", "https://x/")]));
        for forbidden in [
            "ReadWritePaths",
            "ProtectSystem",
            "ProtectHome",
            "PrivateTmp",
            "NoNewPrivileges",
        ] {
            assert!(
                !out.contains(forbidden),
                "{forbidden} must not be generated"
            );
        }
    }

    #[test]
    fn mount_names_that_would_escape_a_path_are_rejected() {
        for bad in [
            "", "-leading", "a/b", "a@b", "..", ".", "a%b", "a b", "a\nb",
        ] {
            assert!(validate_name(bad).is_err(), "{bad:?} should be rejected");
        }
        for good in ["personal", "work-cloud", "my_mount", "nc.example"] {
            assert!(validate_name(good).is_ok(), "{good:?} should be accepted");
        }
    }

    #[test]
    fn the_dropin_directory_uses_service_d() {
        // systemd requires <full-unit-name>.d, so `.service.d` and not `.d`.
        let dir = dropin_dir("personal").unwrap();
        assert!(
            dir.ends_with("davfs-sync@personal.service.d"),
            "wrong drop-in directory: {}",
            dir.display()
        );
    }
}
